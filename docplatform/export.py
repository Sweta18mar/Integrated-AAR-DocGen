"""Renderers for the approved draft. Maps to the Export Lambda (DOCX, PPTX, Markdown)."""

from __future__ import annotations

import re
from pathlib import Path


def to_markdown(draft: dict) -> str:
    out = [f"# {draft['title']}", ""]
    for s in draft["sections"]:
        out += [f"## {s['heading']}", "", s["content"], ""]
    if draft.get("sources"):
        out += ["## Sources", ""]
        out += [f"- [{k}] {v['source']}" for k, v in sorted(draft["sources"].items(), key=lambda kv: int(kv[0][1:]))]
    return "\n".join(out).strip() + "\n"


def _add_runs(paragraph, text: str) -> None:
    """Render **bold** spans; everything else as plain text."""
    for i, part in enumerate(re.split(r"\*\*(.+?)\*\*", text)):
        if part:
            paragraph.add_run(part).bold = i % 2 == 1


def to_docx(draft: dict, path: Path) -> Path:
    import docx

    document = docx.Document()
    document.add_heading(draft["title"], level=0)
    for s in draft["sections"]:
        document.add_heading(s["heading"], level=1)
        for line in s["content"].splitlines():
            stripped = line.strip()
            if not stripped:
                continue
            heading = re.match(r"^(#{1,4})\s+(.*)", stripped)
            if heading:
                document.add_heading(heading.group(2), level=min(len(heading.group(1)) + 1, 4))
            elif re.match(r"^[-*•]\s+", stripped):
                _add_runs(document.add_paragraph(style="List Bullet"), re.sub(r"^[-*•]\s+", "", stripped))
            elif re.match(r"^\d+[.)]\s+", stripped):
                _add_runs(document.add_paragraph(style="List Number"), re.sub(r"^\d+[.)]\s+", "", stripped))
            else:
                _add_runs(document.add_paragraph(), stripped)
    if draft.get("sources"):
        document.add_heading("Sources", level=1)
        for key, src in sorted(draft["sources"].items(), key=lambda kv: int(kv[0][1:])):
            document.add_paragraph(f"[{key}] {src['source']}", style="List Bullet")
    document.save(str(path))
    return path


def to_pptx(draft: dict, slides: list[dict], path: Path) -> Path:
    from pptx import Presentation
    from pptx.util import Pt

    deck = Presentation()
    title_slide = deck.slides.add_slide(deck.slide_layouts[0])
    title_slide.shapes.title.text = draft["title"]
    title_slide.placeholders[1].text = "Draft generated by the document platform · reviewed and approved"

    for spec in slides:
        slide = deck.slides.add_slide(deck.slide_layouts[1])
        slide.shapes.title.text = spec["title"]
        body = slide.placeholders[1].text_frame
        body.clear()
        for i, bullet in enumerate(spec["bullets"] or ["(no content)"]):
            para = body.paragraphs[0] if i == 0 else body.add_paragraph()
            para.text = bullet
            para.font.size = Pt(18)
        if spec.get("notes"):
            slide.notes_slide.notes_text_frame.text = spec["notes"]

    if draft.get("sources"):
        slide = deck.slides.add_slide(deck.slide_layouts[1])
        slide.shapes.title.text = "Sources"
        body = slide.placeholders[1].text_frame
        body.clear()
        for i, (key, src) in enumerate(sorted(draft["sources"].items(), key=lambda kv: int(kv[0][1:]))):
            para = body.paragraphs[0] if i == 0 else body.add_paragraph()
            para.text = f"[{key}] {src['source']}"
            para.font.size = Pt(14)
    deck.save(str(path))
    return path
